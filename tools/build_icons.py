#!/usr/bin/env python3
"""Bundle the Phosphor SVGs in app/icons/ into app/js/icons.js.

To add an icon: download it from https://phosphoricons.com (regular weight, or -fill),
save it as app/icons/<name>.svg, then run:  python3 tools/build_icons.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "app", "icons")
OUT = os.path.join(ROOT, "app", "js", "icons.js")

icons = {}
for fn in sorted(os.listdir(SRC)):
    if fn.endswith(".svg"):
        svg = open(os.path.join(SRC, fn), encoding="utf-8").read().strip()
        inner = re.sub(r"^<svg[^>]*>|</svg>$", "", svg)  # keep only the paths; the <svg> wrapper is added in ui.js
        icons[fn[:-4]] = inner

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/build_icons.py from app/icons/*.svg (Phosphor Icons, MIT). Do not edit by hand.\n")
    f.write("export const ICONS = " + json.dumps(icons, indent=0) + ";\n")
print(f"{len(icons)} icons -> app/js/icons.js")
